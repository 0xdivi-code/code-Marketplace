#!/usr/bin/env node
/**
 * Generates fetch-ref-images.sh from src/data/ref-images.ts so the download list
 * can never drift from what the app actually references.
 *
 *   node scripts/gen-fetch-script.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../src/data/ref-images.ts", import.meta.url), "utf8");

// Resolve the manifest's template shorthands (const U/T/C/... + backticks) into
// literal URLs so the shell script never sees a ${...} it cannot expand.
const vars = new Map();
for (const m of src.matchAll(/^const ([A-Za-z]\w*) = (.+?);$/gm)) {
  const [, name, raw] = m;
  vars.set(name, raw.trim().replace(/^[`"']|[`"']$/g, ""));
}

// Values nest (T is built from U), and String.replace does not re-scan its own
// replacement, so resolve repeatedly until nothing is left.
const resolve = (raw) => {
  let out = raw;
  for (let depth = 0; depth < 10; depth++) {
    if (!/\$\{[A-Za-z]\w*\}/.test(out)) break;
    out = out.replace(/\$\{([A-Za-z]\w*)\}/g, (_, name) => {
      const v = vars.get(name);
      if (v === undefined) {
        console.error(`Unknown template variable \${${name}} — add it to the manifest preamble.`);
        process.exit(1);
      }
      return v;
    });
  }
  if (/\$\{/.test(out)) {
    console.error(`Could not fully resolve: ${raw}`);
    process.exit(1);
  }
  return out;
};

const entries = [...src.matchAll(/\{\s*file:\s*"([^"]+)",\s*remote:\s*`([^`]+)`/g)].map(
  ([, file, remote]) => ({ file, remote: resolve(remote) }),
);

if (!entries.length) {
  console.error("No entries found — did the manifest format change?");
  process.exit(1);
}

const lines = [
  "#!/usr/bin/env bash",
  "# Generated by scripts/gen-fetch-script.mjs — do not edit by hand.",
  "#",
  "# Downloads the reference imagery used as layout/art-direction reference into",
  "# public/img/ref/. Run from the PROJECT ROOT (the folder with package.json):",
  "#",
  "#   bash scripts/fetch-ref-images.sh",
  "#",
  "# Safe to re-run: already-downloaded files are skipped.",
  "set -uo pipefail",
  "",
  'ORIGIN="https://demo.storekitt.app"',
  "",
  '# Always run from the project root, no matter where the script is invoked from.',
  'cd "$(dirname "$0")/.." || exit 1',
  '[ -f package.json ] || { echo "Not in the project root (no package.json)."; exit 1; }',
  "",
  'OUT="public/img/ref"',
  'mkdir -p "$OUT"',
  "",
  "ok=0; skip=0; fail=0",
  "",
  "get() {",
  '  local file="$1" remote="$2"',
  '  if [ -s "$OUT/$file.webp" ] && head -c 4 "$OUT/$file.webp" | grep -q RIFF; then',
  "    skip=$((skip+1)); return",
  "  fi",
  '  if curl -fsSL --retry 2 --max-time 30 "$ORIGIN/$remote" -o "$OUT/$file.webp"; then',
  // A 200 is not proof of an image. Server-side SPA routing returns index.html
  // for a path that does not exist, and `curl -f` only rejects 4xx/5xx, so a
  // miss is saved as "<name>.webp" and every check downstream then passes.
  // Verify the RIFF/WEBP container rather than trusting the status code.
  '    if head -c 4 "$OUT/$file.webp" | grep -q RIFF; then',
  "      ok=$((ok+1))",
  "    else",
  '      echo "  !! not a webp (server returned HTML): $remote"',
  "      rm -f \"$OUT/$file.webp\"",
  "      fail=$((fail+1))",
  "    fi",
  "  else",
  '    echo "  !! failed: $remote"',
  "    rm -f \"$OUT/$file.webp\"",
  "    fail=$((fail+1))",
  "  fi",
  "}",
  "",
  `echo "Fetching ${entries.length} reference images into $OUT ..."`,
  "",
];

for (const { file, remote } of entries) {
  lines.push(`get "${file}" "${remote}"`);
}

lines.push(
  "",
  'echo ""',
  'echo "downloaded: $ok   skipped: $skip   failed: $fail"',
  'echo "total files: $(find "$OUT" -name \'*.webp\' | wc -l | tr -d \' \')"',
  "",
  'if [ "$fail" -gt 0 ]; then',
  '  echo "Some files failed — the app falls back to generated art for those."',
  "  exit 1",
  "fi",
  "",
);

writeFileSync(new URL("./fetch-ref-images.sh", import.meta.url), lines.join("\n"), { mode: 0o755 });
console.log(`Wrote scripts/fetch-ref-images.sh with ${entries.length} images.`);
